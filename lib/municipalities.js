const key = value => String(value || '').normalize('NFD').replace(/\p{Diacritic}/gu, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const aliases = new Map();
for (const town of municipalities) {
  for (const name of [town.name, ...town.aliases]) {
    const value = key(name);
    if (!aliases.has(value)) aliases.set(value, []);
    if (!aliases.get(value).includes(town)) aliases.get(value).push(town);
  }
}
export function provinceMunicipality(race) {
  const matches = aliases.get(key(race.town)) || [];
  return matches.find(town => Math.abs(town.lat - race.lat) < 0.4 && Math.abs(town.lon - race.lon) < 0.5);
}
